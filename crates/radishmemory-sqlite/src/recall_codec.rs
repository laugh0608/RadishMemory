//! Frozen han-basic-a/1 transform. See ADR 0009; not a general Chinese segmenter.
use std::fmt::Write;

use crate::SqliteError;
use rusqlite::{Connection, params};

const MAX_QUERY_BYTES: usize = 4096;
const MAX_QUERY_TERMS: usize = 128;

fn is_han(character: char) -> bool {
    matches!(character, '\u{3400}'..='\u{4dbf}' | '\u{4e00}'..='\u{9fff}')
}

fn runs(text: &str) -> impl Iterator<Item = (bool, &str)> {
    let mut remaining = text;
    std::iter::from_fn(move || {
        let han = is_han(remaining.chars().next()?);
        let end = remaining
            .char_indices()
            .find(|(_, character)| is_han(*character) != han)
            .map_or(remaining.len(), |(offset, _)| offset);
        let run = &remaining[..end];
        remaining = &remaining[end..];
        Some((han, run))
    })
}

fn han_tokens(run: &str) -> String {
    let mut tokens = String::new();
    for character in run.chars() {
        if !tokens.is_empty() {
            tokens.push(' ');
        }
        write!(tokens, "h{:x}", u32::from(character)).expect("write to String");
    }
    tokens
}

pub(crate) fn fields(text: &str) -> (String, String) {
    let mut han = String::new();
    let mut words = String::new();
    for (is_han, run) in runs(text) {
        if is_han {
            if !han.is_empty() {
                han.push_str(" b ");
            }
            han.push_str(&han_tokens(run));
            // A Han barrier cannot be generated by the non-Han query compiler.
            words.push_str(" 界 ");
        } else {
            words.push_str(run);
        }
    }
    (han, words)
}

fn quoted(text: &str) -> String {
    format!("\"{}\"", text.replace('"', "\"\""))
}

/// Use the same locked SQLite tokenizer as the stored word column. The scratch
/// database contains only one bounded query; it never sees a library body/path.
pub(crate) fn expression(query: &str) -> Result<Option<String>, SqliteError> {
    if query.len() > MAX_QUERY_BYTES {
        return Err(SqliteError::search_query_limit());
    }
    let tokenizer = Connection::open_in_memory().map_err(SqliteError::search)?;
    tokenizer
        .execute_batch(
            "CREATE VIRTUAL TABLE query_terms USING fts5(text, tokenize='unicode61');
         CREATE VIRTUAL TABLE query_tokens USING fts5vocab(query_terms, 'instance');",
        )
        .map_err(SqliteError::search)?;
    let mut clauses = Vec::new();
    for (han, run) in runs(query) {
        if han {
            clauses.push(format!("han_terms : {}", quoted(&han_tokens(run))));
        } else {
            for part in run.split_whitespace() {
                tokenizer
                    .execute("DELETE FROM query_terms", [])
                    .map_err(SqliteError::search)?;
                tokenizer
                    .execute(
                        "INSERT INTO query_terms(rowid, text) VALUES (1, ?1)",
                        params![part],
                    )
                    .map_err(SqliteError::search)?;
                let tokens = tokenizer
                    .prepare("SELECT term FROM query_tokens WHERE doc=1 ORDER BY offset")
                    .map_err(SqliteError::search)?
                    .query_map([], |row| row.get::<_, String>(0))
                    .map_err(SqliteError::search)?
                    .collect::<Result<Vec<_>, _>>()
                    .map_err(SqliteError::search)?;
                if !tokens.is_empty() {
                    clauses.push(format!(
                        "word_terms : {}",
                        tokens
                            .iter()
                            .map(|token| quoted(token))
                            .collect::<Vec<_>>()
                            .join(" + ")
                    ));
                }
                if clauses.len() > MAX_QUERY_TERMS {
                    return Err(SqliteError::search_query_limit());
                }
            }
        }
        if clauses.len() > MAX_QUERY_TERMS {
            return Err(SqliteError::search_query_limit());
        }
    }
    Ok((!clauses.is_empty()).then(|| clauses.join(" AND ")))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn matches(body: &str, query: &str) -> bool {
        let connection = Connection::open_in_memory().unwrap();
        connection.execute_batch("CREATE VIRTUAL TABLE test_recall USING fts5(han_terms,word_terms,tokenize='unicode61')").unwrap();
        let (han, words) = fields(body);
        connection
            .execute("INSERT INTO test_recall VALUES(?1,?2)", params![han, words])
            .unwrap();
        expression(query).unwrap().is_some_and(|query| {
            connection
                .query_row(
                    "SELECT EXISTS(SELECT 1 FROM test_recall WHERE test_recall MATCH ?1)",
                    [query],
                    |row| row.get(0),
                )
                .unwrap()
        })
    }

    #[test]
    fn native_unicode61_tokens_keep_private_use_accents_and_literal_operators() {
        for (body, query, expected) in [
            ("café", "cafe", true),
            ("\u{e000} token", "\u{e000}", true),
            ("e\u{301}", "é", true),
            ("API SQL", "API OR SQL", false),
            ("OR", "\" OR \"", true),
            ("APIs", "API", false),
            ("foo中文bar", "foo-bar", false),
            ("foo中文bar", "foo bar", true),
            ("界", "b h754c", false),
            ("h754c b", "h754c", true),
            ("蓝色", "，！", false),
            ("蓝\u{fe0f}色", "蓝色", false),
            ("蓝\u{301}色", "蓝色", false),
            ("蓝\u{200d}色", "蓝色", false),
            ("蓝\0色", "蓝色", false),
            ("蓝色", "蓝\0色", true),
        ] {
            assert_eq!(
                matches(body, query),
                expected,
                "synthetic pair: {body:?}/{query:?}"
            );
        }
    }

    #[test]
    fn frozen_han_ranges_do_not_drift_with_host_unicode_version() {
        for codepoint in [0x3400, 0x4dbf, 0x4e00, 0x9fff] {
            let character = char::from_u32(codepoint).unwrap();
            assert!(matches(&format!("甲{character}乙"), &character.to_string()));
        }
        // Extension B is deliberately outside this profile: the original whole
        // unicode61 token remains available, without silently gaining substring search.
        assert!(matches("\u{20000}\u{20001}", "\u{20000}\u{20001}"));
        assert!(!matches("\u{20000}\u{20001}", "\u{20000}"));
        assert!(matches("繁體資料", "資料"));
        assert!(!matches("繁體資料", "资料"));
    }

    #[test]
    fn query_limits_reject_instead_of_silently_truncating() {
        assert!(expression(&"a".repeat(MAX_QUERY_BYTES)).unwrap().is_some());
        assert_eq!(
            expression(&"a".repeat(MAX_QUERY_BYTES + 1))
                .unwrap_err()
                .code(),
            crate::SqliteErrorCode::SearchQueryLimit
        );
        assert!(expression(&vec!["x"; MAX_QUERY_TERMS].join(" ")).is_ok());
        assert_eq!(
            expression(&vec!["x"; MAX_QUERY_TERMS + 1].join(" "))
                .unwrap_err()
                .code(),
            crate::SqliteErrorCode::SearchQueryLimit
        );
        assert!(expression("   ，！\" : * \u{301}").unwrap().is_none());
    }
}
